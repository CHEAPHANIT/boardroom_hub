// Lightweight bilingual support (English / Khmer) – no extra npm package needed.
import { reactive } from 'vue'
import en from './en.js'
import km from './km.js'
import { serverKm, notificationKm } from './server-km.js'

const messages = { en, km }
const LANGS = ['en', 'km']

function initialLocale() {
  try {
    const saved = localStorage.getItem('bh_lang')
    if (LANGS.includes(saved)) return saved
  } catch { /* storage blocked */ }
  return 'en'
}

export const i18n = reactive({ locale: initialLocale() })

function lookup(obj, path) {
  return path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj)
}

/** Translate a key, e.g. t('nav.meetings') or t('common.pageOf', { page: 1 }) */
export function t(key, params) {
  let s = lookup(messages[i18n.locale], key)
  if (typeof s !== 'string') s = lookup(en, key)
  if (typeof s !== 'string') return key
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m))
  return s
}

/** Does the current language have a translation for this key? */
export function has(key) {
  return typeof lookup(messages[i18n.locale], key) === 'string' || typeof lookup(en, key) === 'string'
}

export function setLocale(lang) {
  if (!LANGS.includes(lang)) return
  i18n.locale = lang
  try { localStorage.setItem('bh_lang', lang) } catch { /* ignore */ }
  applyDocumentLang()
}

export function applyDocumentLang() {
  document.documentElement.lang = i18n.locale
  document.documentElement.classList.toggle('lang-km', i18n.locale === 'km')
}

/** Locale code for Intl date formatting */
export const dateLocale = () => (i18n.locale === 'km' ? 'km-KH' : 'en-US')

/** Translate a message that came from the API (only when Khmer is selected). */
export function serverText(msg) {
  if (!msg || i18n.locale !== 'km') return msg
  return serverKm(msg)
}

/** Translate a notification title generated by the API. */
export function notificationText(text) {
  if (!text || i18n.locale !== 'km') return text
  return notificationKm(text)
}

/** Role names come from the database; show the Khmer name for the built-in roles. */
export function roleName(name) {
  if (!name) return name
  const key = 'roles.' + name.replace(/\s+/g, '_')
  return has(key) ? t(key) : name
}

export default { install(app) { app.config.globalProperties.$t = t } }
